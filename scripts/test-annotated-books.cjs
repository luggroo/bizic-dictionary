'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const path=require('node:path'),root=path.resolve(__dirname,'../site');
const ctx=vm.createContext({window:{},fetch:async name=>({ok:true,json:async()=>JSON.parse(fs.readFileSync(path.join(root,name),'utf8'))}),E:s=>String(s??'').replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c])),normalizeIPA:s=>s});
vm.runInContext(fs.readFileSync(path.join(root,'longshan-texts.js'),'utf8'),ctx);
const app=fs.readFileSync(path.join(root,'app.js'),'utf8');vm.runInContext(app.match(/function corpusCollectionKey\(c\)\{[^}]+\}/)[0],ctx);
(async()=>{
 const data={corpus:[],sources:[]};await ctx.loadLongshanTexts(data);
 const record=data.corpus.find(c=>c.id==='xu-tujia-annotated-2-1-excerpt');
 assert.ok(record);assert.equal(ctx.corpusCollectionKey(record),'xu-tujia-annotated-texts');
 assert.equal(ctx.corpusCollectionKey(data.corpus.find(c=>c.source==='tlp-longshan')),'tlp-longshan');
 assert.equal(record.blocks.length,129);assert.ok(data.sources.find(s=>s.id===record.source));
 assert.ok(record.blocks.every(b=>b.ipa&&b.originalIpa&&b.zh&&b.glosses.every(g=>g.ipa&&g.zh)));
 const books=data.corpus.filter(c=>c.bookSource);
 assert.equal(new Set(books.map(c=>c.id)).size,books.length,'book IDs must be unique');
 for(let n=1;n<=14;n++)assert.ok(books.find(c=>c.code==='2.'+n),'2.'+n+' is present');
 const ids=books.flatMap(c=>c.blocks.map(b=>b.id));assert.equal(new Set(ids).size,ids.length,'fragment IDs must be unique');
 for(const c of books)for(const b of c.blocks)assert.equal(b.ipa,b.glosses.map(g=>g.ipa).join(' '),b.id+' word alignment');
 const eye=books.find(c=>c.code==='2.2').blocks.find(b=>b.id==='2.2-007');
 assert.equal(eye.glosses[0].zh,'眼睛');assert.equal(eye.glosses[0].originalGloss,'鼻子');
 const html=ctx.longshanTextDetail(record);
 for(const piece of ['土家语语法标注文本','ɣɨ³⁵','INJ','以前土家族人得了一场病'])assert.ok(html.includes(piece),piece);
 assert.ok(!html.includes('Tujia Language Project'));assert.ok(!html.includes('复核稿'));assert.ok(!html.includes('原书记音'));assert.ok(html.includes('本站拼音'));
 const withSpelling=ctx.longshanTextDetail({...record,blocks:[{...record.blocks[0],pinyin:'bi³⁵zi⁵⁵ka²¹',reviewNote:'待核读音'}]});
 assert.ok(withSpelling.includes('原书拼音')&&withSpelling.includes('bi³⁵zi⁵⁵ka²¹')&&!withSpelling.includes('待核读音'));
 const unusual=books.find(c=>c.code==='2.14').blocks.find(b=>b.id==='2.14-071');
 assert.equal(unusual.ipaStatus,'部分记音待规范');assert.ok(!ctx.longshanTextDetail(books.find(c=>c.code==='2.14')).includes('原书记音'));
 await ctx.loadLongshanTexts(data);assert.equal(data.corpus.filter(c=>c.id===record.id).length,1);
 console.log('PASS: annotated book provenance, grouping, alignment, IPA, rendering and deduplication');
})().catch(e=>{console.error(e);process.exitCode=1});
