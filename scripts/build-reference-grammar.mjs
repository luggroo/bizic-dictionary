// Compile the reviewed Markdown; requires the `marked` Markdown parser.
// The public artifact excludes the review log and editorial instructions.
import fs from 'node:fs';
import path from 'node:path';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const markedPath=require.resolve('marked',{paths:[process.env.CODEX_PRIMARY_RUNTIME_NODE_MODULES||process.cwd()]});
const {marked}=await import(markedPath);
const root=path.resolve(path.dirname(new URL(import.meta.url).pathname),'..');
let md=fs.readFileSync(path.join(root,'docs/reference-grammar.md'),'utf8');
md=md.split('<a id="review-notes"')[0];
const northern=md.split('# 北部土家语\n')[1].split('# 南部土家语\n')[0];
const southern=md.split('# 南部土家语\n')[1].split('<a id="phonology-appendix"')[0];
const southAppendix=md.split('## 附录 B：南部语音与记音\n')[1].replace(/\n---\s*$/,'');
const esc=s=>String(s).replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
function html(source){
 source=source.replace(/^\[\^([^\]]+)\]: (.+)$/gm,(_,id,text)=>`<details class="grammar-reference"><summary>文献出处</summary><p id="fn-${id}">${marked.parseInline(text)}</p></details>\n`);
 source=source.replace(/\[\^([^\]]+)\]/g,(_,id)=>`<sup><a href="#fn-${id}" aria-label="文献注释">[注]</a></sup>`);
 // These sentences only describe the former draft's organization.
 source=source.replace(/^本节统一使用下列术语。/m,'').replace(/^本节统一按陈康的分类，将方向性的diu称为完成向心、lu称为完成离心。/m,'陈康将方向性的diu称为完成向心、lu称为完成离心。');
 source=source.replace(/例句中将 \/a⁵⁵tiu⁵⁵\/、\/a⁵⁵lu²¹\/ 各列为一个分析单位，分别标“完成向心”“完成离心”。/g,'/a⁵⁵tiu⁵⁵/、/a⁵⁵lu²¹/ 分别整体表示完成向心、完成离心。');
 return marked.parse(source,{gfm:true});
}
const result={north:[],south:[]},anchors={},legacy={north:{},south:{}};
for(const [d,source,offset] of [['north',northern,100],['south',southern,200]]){
 const marks=[...source.matchAll(/^## (\d+)\. (.+)$/gm)];
 for(let i=0;i<marks.length;i++){
  const m=marks[i],id=String(offset+Number(m[1]));
  let body=source.slice(m.index+m[0].length,marks[i+1]?.index??source.length).trim().replace(/\n---\s*$/,'');
  // A chapter anchor is printed immediately before its Markdown heading.
  const headAnchors=(source.slice(i?marks[i-1].index:0,m.index).match(/(?:<a id="[^"]+"><\/a>\s*)+$/)||[''])[0];
  body=headAnchors+'\n'+body;
  if(i+1<marks.length)body=body.replace(/(?:<a id="[^"]+"><\/a>\s*)+$/,'');
  const pending=/^\s*(?:<a[^\n]+\n\s*)*本部分暂无现成正文。\s*$/.test(body);
  if(d==='south'&&i===0)body+='\n\n<details>\n<summary>声母、韵母与声调列表</summary>\n\n'+southAppendix+'\n\n</details>\n';
  if(pending)body=headAnchors;
  const content=html(body);
  const sections=[...body.matchAll(/^### (\d+\.\d+) (.+)$/gm)].map(x=>({id:id+'.'+x[1].split('.')[1],title:x[2],query:x[2]}));
  const chapter={id,number:m[1],title:m[2],dialect:d,key:d+'-'+id,part:0,intro:'',sections,html:content,pending,pattern:'Brassett|土家语|Tujia'};
  result[d].push(chapter);
  for(const a of content.matchAll(/\bid="([^"]+)"/g)){
   if(anchors[a[1]])throw Error('Duplicate anchor '+a[1]);anchors[a[1]]={dialect:d,chapter:id};
   const old=a[1].match(/^(?:fn-ref-)?(?:north|south)-(\d+)[.-]/);
   if(old&&!legacy[d][old[1]])legacy[d][old[1]]=id;
  }
 }
}
anchors['north-part-5']={dialect:'north',chapter:'106'};
// Historic chapter bookmarks point to the new primary home of each subject.
Object.assign(legacy.north,{'1':'101','2':'101','3':'101','4':'101','5':'101','6':'104','7':'103','8':'103','9':'104','10':'103','11':'103','12':'103','13':'103','14':'103','15':'103','16':'104','17':'104','18':'102','19':'102','20':'105','21':'104','22':'105','23':'104','24':'106','25':'106','26':'106','27':'107','28':'107','29':'104','30':'106'});
Object.assign(legacy.south,{'1':'201','2':'201','3':'201','4':'201','5':'201','6':'203','7':'202','8':'202','9':'203','10':'202','11':'202','12':'202','13':'202','14':'202','15':'202','16':'203','17':'203','18':'203','19':'206','20':'204','21':'203','22':'204','23':'203','24':'205','25':'205','26':'205','27':'206','28':'206','29':'203','30':'205'});
const predicateTable=md.split('#### 谓词变化总表')[1]?.split('#### ')[0]||'';
const paradigmForms=[...predicateTable.matchAll(/^\|[^|]+\|([^|]+)\|/gm)].flatMap(m=>m[1].match(/\b[a-z]+[xfrv]\b/g)||[]);
const lexiconForms=[...md.matchAll(/\[([a-z]+[xfrv])\]\(\?id=[^)]*#words\)/g)].map(m=>m[1]);
const yeForms=[...new Set([...md.matchAll(/^\| 拼音 \| (.+)$/gm)].flatMap(m=>m[1].match(/[a-z]+/g)||[]).concat(paradigmForms,lexiconForms,['ngafdor','angfdor','nifdor','sefdor','gofdor','gexdor','angfnix','angf','gexzex','gex']))];
const output='const GRAMMAR_YE_FORMS='+JSON.stringify(yeForms)+';\n// Generated by scripts/build-reference-grammar.mjs from docs/reference-grammar.md.\nconst REVIEWED_GRAMMAR='+JSON.stringify(result)+';\nconst GRAMMAR_ANCHORS='+JSON.stringify(anchors)+';\nconst GRAMMAR_LEGACY_CHAPTERS='+JSON.stringify(legacy)+';\n';
fs.writeFileSync(path.join(root,'site/grammar-reviewed-data.js'),output);
console.log(result.north.length+' northern, '+result.south.length+' southern chapters; '+Object.keys(anchors).length+' anchors.');
